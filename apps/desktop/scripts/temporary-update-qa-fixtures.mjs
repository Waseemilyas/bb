import { cp, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(root, 'package.json'));
const builderRequire = createRequire(require.resolve('electron-builder'));
const libRequire = createRequire(builderRequire.resolve('app-builder-lib'));
const asar = libRequire('@electron/asar');
const fixtureRoot = await mkdtemp(join(root, '.update-qa-'));
const output = join(root, 'release', 'update-qa');
const packageInfo = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
const target = packageInfo.version;
const oldVersion = '0.0.1';
const originalConfig = JSON.parse(await readFile(join(root, 'electron-builder.config.json'), 'utf8'));
for (const version of [oldVersion, target]) {
  const staging = join(fixtureRoot, version);
  await cp(join(root, 'release', 'linux-unpacked'), staging, { recursive: true });
  const archive = join(staging, 'resources', 'app.asar');
  const extracted = join(fixtureRoot, `app-${version}`);
  asar.extractAll(archive, extracted);
  const appPackagePath = join(extracted, 'package.json');
  const appPackage = JSON.parse(await readFile(appPackagePath, 'utf8'));
  await writeFile(appPackagePath, JSON.stringify({ ...appPackage, version }));
  const runtimePackagePath = join(extracted, 'node_modules', 'bb-app', 'package.json');
  const runtimePackage = JSON.parse(await readFile(runtimePackagePath, 'utf8'));
  await writeFile(runtimePackagePath, JSON.stringify({ ...runtimePackage, version }));
  const mainPath = join(extracted, 'dist', 'main.js');
  let main = await readFile(mainPath, 'utf8');
  const feed = '`https://github.com/get-bb/bb/releases/download/${releaseTag}/`';
  if (!main.includes(feed)) throw new Error('The compiled desktop feed URL was not found');
  main = main.replaceAll(feed, '"http://127.0.0.1:24791/"');
  if (!main.includes(JSON.stringify(target))) throw new Error('Desktop version was not found');
  main = main.replaceAll(JSON.stringify(target), JSON.stringify(version));
  await writeFile(mainPath, main);
  await rm(archive);
  await rm(`${archive}.unpacked`, { recursive: true, force: true });
  await asar.createPackageWithOptions(extracted, archive, { unpackDir: 'node_modules', unpack: '**/bb-app-bridge.mjs' });
  await readFile(join(`${archive}.unpacked`, 'dist', 'bb-app-bridge.mjs'));
  const config = { ...originalConfig, afterPack: undefined, directories: { ...originalConfig.directories, output }, publish: [{ provider: 'generic', url: 'http://127.0.0.1:24791/' }] };
  const configPath = join(fixtureRoot, 'builder.json');
  await writeFile(configPath, JSON.stringify(config));
  execFileSync(process.execPath, [join(root, 'node_modules', 'electron-builder', 'cli.js'), '--linux', 'AppImage', '--x64', '--prepackaged', staging, '--config', configPath, '--publish', 'never', `--config.extraMetadata.version=${version}`], { cwd: root, stdio: 'inherit' });
  await rm(staging, { recursive: true, force: true });
  await rm(extracted, { recursive: true, force: true });
}
await writeFile(join(output, 'qa-build.json'), JSON.stringify({ head: process.env.GITHUB_SHA, from: oldVersion, to: target, feed: 'http://127.0.0.1:24791/', modifications: ['release feed points at local fixture server', 'starting desktop and bundled runtime versions set to 0.0.1'] }, null, 2));
await rm(fixtureRoot, { recursive: true, force: true });
